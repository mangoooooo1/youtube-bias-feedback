// 프롬프트 가드레일이 뚫려 시청자의 정치 성향·태도를 추론하는 표현이 LLM 출력에 섞였을 때 잡아내는 최후 방어선.
// 제목에 나온 인물·정당·사건 이름과 콘텐츠 설명("○○을 비판하는 영상")은 사실 서술로 허용하고,
// 시청자에게 성향이나 태도를 돌리는 표현만 막는다. 정규식이라 문장 뜻을 다 알 수는 없어 프롬프트 지시와 함께 쓴다.

// 성향 꼬리표. "성향"·"보수"는 단독으로 막지 않는다("시청 성향", "보수 공사" 오탐 방지)
const IDEOLOGY = String.raw`(?:진보|보수|중도)\s*(?:적|성향|진영|층|편향|이념)|(?:정치|이념)\s*(?:적\s*)?(?:성향|지향|편향|색채)|좌파|우파|좌익|우익|극우|극좌|좌편향|우편향|지지층`;
// 정치적 태도. "지지율", "반대로"(접속어), "반대편"은 뺀다
const ATTITUDE = String.raw`(?:지지(?!율)|반대(?!로|편)|반감|동조|혐오|거부감|불신|적대)`;
// 일상적 선호. 정치 대상이 같은 문장에 있을 때만 막는다("음악을 좋아하시는 것 같아요"는 통과)
const PREFERENCE = String.raw`(?:좋아하|싫어하|미워하|선호|호감)`;
const TARGET = String.raw`(?:정당|진영|이념|정치|정부|후보|대통령|여당|야당|국민의힘|민주당)`;
// 시청자에게 돌린다는 신호. 리뷰는 시청자에게 높임말로 말하므로 높임말이면 주체가 시청자이고, 추측 어미는 추론이다
const GUESS = String.raw`(?:하시|하셨|하실|가지시|가지신|가지셨|있으시|있으신|이시|이신|것\s?같|듯|보여|보이|짐작|추측|가능성|수도|수\s?있|는\s?편)`;
const VIEWER = String.raw`(?:시청자|사용자|참여자|당신)`;
// 같은 문장 안
const S = String.raw`[^.!?]`;

const SENSITIVE_PATTERN = new RegExp(
  [
    IDEOLOGY,
    // "지지하시는", "반감을 가지신 듯", "지지하지 않는 것 같", "지지자일 수도"
    `${ATTITUDE}${S}{0,12}?${GUESS}`,
    // "국민의힘을 싫어하시는", "후보에 호감이 있으신 것 같"
    `${TARGET}${S}{0,15}?${PREFERENCE}(?:시|셨|실|${S}{0,10}?${GUESS})`,
    // "시청자는 ○○을 지지하지 않는"
    `${VIEWER}${S}{0,20}?${ATTITUDE}`,
  ].join("|"),
);

module.exports = { SENSITIVE_PATTERN };

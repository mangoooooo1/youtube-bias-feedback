// 프롬프트 가드레일이 뚫려 시청자의 정치 성향을 추론하는 표현이 LLM 출력에 섞였을 때 잡아내는 최후 방어선.
// 제목에 나온 인물·정당·사건 이름은 사실 서술로 허용하므로 명사가 아니라 성향을 붙이는 표현만 막는다.
// "성향"·"보수"는 단독으로 막지 않는다("시청 성향", "보수 공사" 오탐 방지).
const SENSITIVE_PATTERN =
  /(?:진보|보수|중도)\s*(?:적|성향|진영|층|편향|이념)|(?:정치|이념)\s*(?:적\s*)?(?:성향|지향|편향|색채)|좌파|우파|좌익|우익|극우|극좌|좌편향|우편향|지지층/;

module.exports = { SENSITIVE_PATTERN };

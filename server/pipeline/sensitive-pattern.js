// 프롬프트 가드레일이 뚫려 시청자의 정치 성향을 추론하는 표현이 LLM 출력에 섞였을 때 잡아내는 최후 방어선.
// 제목에 나온 인물·정당·사건 이름은 사실 서술로 허용하므로 명사가 아니라 성향을 붙이는 표현만 막는다.
// "성향"·"보수"는 단독으로 막지 않는다("시청 성향", "보수 공사" 오탐 방지).
// 지지는 시청자에게 돌리는 표현만 막는다("지지자 집회", "지지율" 같은 제목 속 사실은 통과).
// - 높임말 "지지하시": 리뷰는 시청자에게 높임말로 말하므로 주체가 시청자다
// - "지지자일 것/인 듯/일 수": 추측
// - 시청자·당신 등이 주어인 문장의 "지지"
const SENSITIVE_PATTERN =
  /(?:진보|보수|중도)\s*(?:적|성향|진영|층|편향|이념)|(?:정치|이념)\s*(?:적\s*)?(?:성향|지향|편향|색채)|좌파|우파|좌익|우익|극우|극좌|좌편향|우편향|지지층|지지하(?:시|실|셨)|지지(?:자|하는\s?분|하는\s?사람)(?:이|일|인|이신|이실|으로)\s*(?:것|수|듯|가능성|편)|(?:시청자|사용자|참여자|당신)[^.!?]{0,20}지지/;

module.exports = { SENSITIVE_PATTERN };

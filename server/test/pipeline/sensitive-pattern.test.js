import { describe, it, expect } from "vitest";
import { SENSITIVE_PATTERN } from "../../pipeline/sensitive-pattern.js";

describe("SENSITIVE_PATTERN — 성향 꼬리표", () => {
  it.each([
    "오늘은 보수 성향 콘텐츠를 많이 보셨어요.",
    "진보적인 시각의 영상을 주로 보셨어요.",
    "보수층이 즐겨 보는 채널이에요.",
    "중도 성향에 가까운 시청이에요.",
    "정치 성향이 드러나는 시청이에요.",
    "정치적 성향을 엿볼 수 있어요.",
    "이념 성향이 비슷한 영상이에요.",
    "좌파 유튜버의 영상을 보셨어요.",
    "우편향된 채널이 많았어요.",
    "극우 성향 영상이 많았어요.",
    "특정 정당 지지층이 보는 영상이에요.",
  ])("막는다: %s", (text) => {
    expect(SENSITIVE_PATTERN.test(text)).toBe(true);
  });
});

// 대상(정당·진영·정치인 등) × 태도(지지·반대·반감…) × 시청자 귀속(높임말·추측 어미·시청자 주어)
describe("SENSITIVE_PATTERN — 시청자에게 돌린 정치적 태도", () => {
  it.each([
    // 지지·선호
    "시청자는 민주당 지지자일 것 같아요.",
    "민주당을 지지하시는 것 같아요.",
    "국민의힘 지지자인 듯해요.",
    "당신은 진보 정당을 지지하는 편이에요.",
    "보수 정당을 지지하는 분일 수도 있어요.",
    "○○ 후보를 좋아하시는 것 같아요.",
    // 반대·비선호
    "시청자는 국민의힘을 싫어하는 것 같아요.",
    "국민의힘을 싫어하시는 것 같아요.",
    "여당에 반대하시는 것 같아요.",
    "시청자는 진보 진영에 반감을 가진 것 같아요.",
    "민주당에 반감을 가진 것 같아요.",
    "정부 정책에 반감을 가지신 듯해요.",
    // 동조·거부·불신
    "시청자는 보수 이념에 동조하는 것 같아요.",
    "특정 정당에 거부감이 있으신 것 같아요.",
    "정부를 불신하시는 듯해요.",
    // 부정형도 태도 추론이다
    "시청자는 민주당을 지지하지 않는 것 같아요.",
  ])("막는다: %s", (text) => {
    expect(SENSITIVE_PATTERN.test(text)).toBe(true);
  });
});


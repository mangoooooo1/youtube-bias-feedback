import { describe, it, expect } from "vitest";
import { SENSITIVE_PATTERN } from "../../pipeline/sensitive-pattern.js";

describe("SENSITIVE_PATTERN — 성향 추론 표현만 막는다", () => {
  it.each([
    "오늘은 보수 성향 콘텐츠를 많이 보셨어요.",
    "진보적인 시각의 영상을 주로 보셨어요.",
    "보수층이 즐겨 보는 채널이에요.",
    "중도 성향에 가까운 시청이에요.",
    "정치 성향이 드러나는 시청이에요.",
    "정치적 성향을 엿볼 수 있어요.",
    "이념 성향이 비슷한 영상이에요.",
    "좌파 유튜버의 영상을 보셨어요.",
    "우편향된 채널이 많았어요.",
    "극우 성향 영상이 많았어요.",
    "특정 정당 지지층이 보는 영상이에요.",
  ])("막는다: %s", (text) => {
    expect(SENSITIVE_PATTERN.test(text)).toBe(true);
  });

  it.each([
    "뉴스 중에서도 대통령 기자회견 영상을 주로 보셨어요.",
    "탄핵 심판 선고 뉴스를 여러 번 보셨어요.",
    "국회의원 인터뷰와 여당·야당 대표 연설을 보셨어요.",
    "국민의힘과 민주당 대표 토론 영상을 보셨어요.",
    "정당한 판정인지 다룬 축구 영상을 보셨어요.",
    "정당방위 판례를 설명하는 영상을 보셨어요.",
    "시청 성향을 돌아보면 음악이 가장 많았어요.",
    "아파트 보수 공사 브이로그를 보셨어요.",
  ])("통과시킨다: %s", (text) => {
    expect(SENSITIVE_PATTERN.test(text)).toBe(false);
  });
});
